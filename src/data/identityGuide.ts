export function renderIdentityGuide(identity: IdentityLevel): string {
  const g = identityGuides[identity];
  return [
    `【玩家当前身份：${g.label}】（${g.shortDesc}）`,
    "",
    g.guidance,
    "",
    g.shiftConditions,
    "",
    "【身份变化协议】",
    "若本轮剧情触发了身份升级 / 降级条件，请在 stateChanges.identityShift 字段设新身份；",
    "下一轮 LLM 会读到新身份，narration 视角立即切换。",
    "不要频繁升级——身份变化应当是有'可识别的剧情铺垫'之后的结果。",
  ].join("\n");
}
