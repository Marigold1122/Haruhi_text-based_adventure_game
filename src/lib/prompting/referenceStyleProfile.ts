export function buildStyleRepairPrompt(rawText: string, problems: string[]): ChatMessage[] {
  return [
    {
      role: "system",
      content: [
        "你是中文互动轻小说正文修复器。只修正文风和违规表达，不改变剧情事实、人物行动、场景顺序或信息量。",
        "输出只包含修复后的自然正文，省略 JSON、Markdown、解释、标题和前后缀。",
        REFERENCE_STYLE_PROMPT,
        "修复时聚焦被指出的问题；保持原段落的信息量和叙事顺序。",
      ].join("\n\n"),
    },
    {
      role: "user",
      content: [
        "<需要修复的问题>",
        problems.map((problem) => `- ${problem}`).join("\n"),
        "</需要修复的问题>",
        "",
        "<原正文>",
        rawText.trim(),
        "</原正文>",
        "",
        "请在保留原剧情事实的前提下修复为第一人称、可观察、少升华、无系统词污染的自然正文。",
      ].join("\n"),
    },
  ];
}
